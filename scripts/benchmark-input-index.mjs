import { build } from "esbuild";
import { mkdir, writeFile, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { performance } from "node:perf_hooks";
import { fileURLToPath } from "node:url";

await mkdir("reports", { recursive: true });
const outfile = fileURLToPath(new URL("../reports/input-index-benchmark.cjs", import.meta.url));
await build({ stdin: { contents: 'export { CurrentVaultWordProvider } from "./src/provider/CurrentVaultWordProvider";', resolveDir: process.cwd() }, bundle: true, platform: "node", format: "cjs", outfile });
const { CurrentVaultWordProvider } = createRequire(import.meta.url)(outfile);
const files = Array.from({ length: 500 }, (_, i) => ({ path: `${i}.md`, stat: { mtime: 1, size: 5000 } }));
const app = { vault: { getMarkdownFiles: () => files, cachedRead: async (file) => file.path } };
const helper = { getCurrentDirname: () => "." };
const tokenizer = { tokenize: (path) => Array.from({ length: 500 }, (_, n) => `词语${path}-${n}`), shouldIgnoreOnCurrent: () => false };
const provider = new CurrentVaultWordProvider(app, helper);
provider.setSettings(tokenizer, [], [], [], false);
const options = { minNumberOfCharacters: 2, makeSynonymAboutEmoji: false, makeSynonymAboutAccentsDiacritics: false, excludeWordPatterns: [] };
await provider.refreshWords(options);
files[0].stat.mtime++;
let previous = performance.now(), longestGap = 0;
const timer = setInterval(() => { const now = performance.now(); longestGap = Math.max(longestGap, now - previous); previous = now; }, 1);
const start = performance.now();
await provider.refreshWords(options);
await new Promise((resolve) => setTimeout(resolve, 5));
clearInterval(timer);
const report = { indexedWords: provider.wordCount, changedFiles: 1, refreshMilliseconds: +(performance.now() - start).toFixed(2), longestEventLoopGapMilliseconds: +longestGap.toFixed(2) };
const phase = process.argv.includes("--baseline") ? "baseline" : "optimized";
await writeFile(`reports/input-index-${phase}.json`, JSON.stringify(report, null, 2));
await rm(outfile);
console.log(JSON.stringify(report, null, 2));
